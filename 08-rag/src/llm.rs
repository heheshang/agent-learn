//! LLM 抽象层 —— 直接复用 07-query 的实现。
//!
//! ## 为什么复用而不是抄一份
//!
//! 07-query 的 [`rag_07::llm`] 已经把 LLM 调用收敛成一个 trait：
//!
//! ```text
//! 生产：GenaiLlm      → 真的调 DeepSeek / OpenAI
//! 测试：ScriptedLlm   → 按脚本返回预设答案，零网络、零延迟、完全确定
//! ```
//!
//! 本项目的生成环节和 07 完全一样（改写 vs 生成不影响 LLM 抽象），
//! 所以直接 `pub use` —— 改一处就生效两处。
//!
//! ## 但本项目**没有**查询改写
//!
//! 注意 08 **不用** LLM 做查询改写 —— 它的查询是原样送进检索的。
//!
//! 这不是遗漏，而是**教学顺序**：
//!
//! | 项目 | 查询处理 |
//! |---|---|
//! | 07-query | 改写（HyDE / MultiQuery / ...）→ 多路检索 → 融合 |
//! | 08-rag | 原样查询 → **双路**检索 → 融合 → **重排** |
//!
//! 08 的重点是**检索侧**的改进：加一路 BM25、加一层 cross-encoder。
//! 查询侧的问题留给 07 解决 —— 两个项目**可以叠加**：
//! 改写之后的每个查询都走一遍混合检索 + 重排。


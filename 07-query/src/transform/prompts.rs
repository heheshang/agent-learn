//! 改写提示词（Prompts）—— 改写质量的天花板在这里。
//!
//! ## 提示词为什么决定成败
//!
//! 查询改写看起来像「让 LLM 换个说法」，但提示词写得好坏，
//! 检索召回率能差出一倍。
//!
//! 差的提示词（最常见的错误写法）：
//!
//! ```text
//! 请改写下面的问题：
//! {question}
//! ```
//!
//! 这会让 LLM 输出「模型如何解决知识截止日期问题？」这样的
//! **陈述式检索式** —— 而索引里存的是文档原文（陈述句、术语、长句）。
//! 用户的问法是疑问句，文档的写法是陈述句 —— 两种文体在向量空间里
//! 本来就有一段距离。
//!
//! 好的提示词要做三件事：
//!
//! 1. **明确输出格式** —— 编号列表、每行一条、不要解释
//! 2. **对齐目标文体** —— 告诉 LLM 检索目标是「文档原文」，不是「问法」
//! 3. **给出正反例** —— 告诉 LLM 什么样的改写是好的
//!
//! ## 三个提示词的共同骨架
//!
//! ```text
//! [角色]   你是……检索助手
//! [任务]   把下面的问题改写成……
//! [格式]   必须输出 N 行，每行一个，不要编号不要解释
//! [示例]   输入 → 输出
//! [输入]   {question}
//! ```
//!
//! 这个骨架不是随便定的 —— 它对应提示词工程里被反复验证的四要素：
//! 角色（Role）、任务（Task）、格式（Format）、示例（Few-shot）。

/// HyDE 的提示词。
///
/// ## HyDE 在干什么
///
/// HyDE（Hypothetical Document Embeddings）的核心洞察是：
///
/// > 向量检索在「问题 ↔ 文档」之间对齐很难，但在
/// > 「文档 ↔ 文档」之间对齐很容易。
///
/// 所以与其问「怎么把问题变成文档」，不如**直接生成一段假想的答案文档**，
/// 用它去检索真实的文档。
///
/// ## 例子
///
/// 问题：`模型的知识有截止日期怎么办`
///
/// HyDE 生成：
///
/// ```text
/// 模型的知识截止日期问题可以通过检索增强生成（RAG）来解决。
/// RAG 在生成答案前先从外部知识库检索相关文档片段，
/// 把这些片段作为上下文提供给语言模型，从而补充模型训练数据之外的信息。
/// ```
///
/// 这段话和知识库里的原文**文体一致、内容接近**，所以向量更近。
///
/// ## 提示词要点
///
/// - 要求「假装你是知识库里的文档」—— 强制文体对齐
/// - 明确「不要回答问题」—— 否则 LLM 会直接给答案，而不是写文档
/// - 要求「200 字左右」—— 太短信息量不足，太长会引入噪声
/// - 允许「不知道就说不知道」—— 避免 LLM 为了凑字数编造内容
pub const HYDE_PROMPT: &str = "\
你是一个技术知识库的检索助手。用户会问一个问题，你的任务是**写一段假想的知识库文档**，
用来在向量库里检索出相关片段。

请严格遵守以下规则：

1. **不要回答这个问题**。你的任务是模拟一段「知识库里本来就有的说明性文字」，
   而不是给出答案本身。
2. 用**陈述句**写作，语气和定义、说明、原理介绍一类的文档一致。
3. 长度控制在 150~250 字，包含相关的**专业术语**和**概念解释**，
   这些术语很可能就是知识库原文里出现的词。
4. 如果你不确定知识库里有什么内容，就写通用的原理性说明，
   **不要编造具体数字、版本号、人名**。
5. **只输出这段文档正文**，不要任何标题、前缀、编号或解释。

示例：

用户问题：分块的大小应该怎么定？
输出：文档分块（chunking）是把长文档切分成若干较小片段的过程，
以便每个片段能够被独立地向量化并检索。分块大小的选择需要在
上下文完整性与检索精度之间取得平衡。块过大会使单个向量混合多个主题，
稀释语义信号；块过小则会割裂答案，使语言模型缺少足够的上下文。
实际使用中常以 token 数量衡量块大小，并保留一定比例的重叠区域，
以确保落在切分边界上的句子仍能完整地出现在相邻块中。

用户问题：{question}
输出：";

/// Multi-Query 的提示词。
///
/// ## Multi-Query 在干什么
///
/// 一个问题往往有多种「问法」，而每种问法在向量空间里落点不同。
/// Multi-Query 让 LLM 生成 N 个**语义等价但措辞不同**的问法，
/// 每个都去检索一次，最后把多路结果融合。
///
/// 关键在于「**等价但不同**」：
///
/// - 太接近（比如「什么是 RAG」和「什么是 RAG 呢」）→ 多路检索结果几乎一样，白花成本
/// - 差别太大（变成不同的问题）→ 召回了噪声，稀释了融合结果
///
/// 所以提示词里明确要求「覆盖不同的措辞、术语、视角」。
///
/// ## 格式要求
///
/// 必须编号列表 —— 因为 [`crate::transform::parse_numbered_lines`] 靠编号切分。
/// 这也顺便逼 LLM 明确输出数量。
pub const MULTI_QUERY_PROMPT: &str = "\
你是一个技术知识库的检索助手。用户会问一个问题，你的任务是生成 **3 个语义等价但措辞不同**的检索问法。

请严格遵守以下规则：

1. 生成**恰好 3 个**问法。
2. 三个问法必须**回答同一个问题**，但要使用不同的措辞、术语或切入角度。
   例如：一个用口语、一个用技术术语、一个用具体场景。
3. 每个问法都是**完整的疑问句**，可以直接拿去向量检索。
4. **不要重复**同一个句式模板，只替换名词。
5. 严格按下面的格式输出，每行一个，编号从 1 开始，**不要任何其他内容**：

```
1. 第一个问法
2. 第二个问法
3. 第三个问法
```

用户问题：{question}
输出：";

/// Rewrite 的提示词。
///
/// ## Rewrite 在干什么
///
/// Rewrite（查询改写）解决的是**指代消解**问题：
///
/// ```text
/// 用户：RAG 和微调有什么区别？
/// 用户：那它训练成本高吗？        ← 「它」是什么？
/// ```
///
/// 直接拿「那它训练成本高吗」去检索，嵌入模型根本不知道「它」指什么 ——
/// 向量里全是「它/那个/这个」这类无信息词。
///
/// Rewrite 让 LLM 把多轮对话的指代补全成一个**自包含**的查询：
/// 「RAG 和微调相比，哪种方式的训练成本更高？」
///
/// 这时候索引里如果恰好有讲微调训练成本的段落，就能召回。
///
/// ## 为什么它只需要一条结果
///
/// Rewrite 是「补全」而不是「扩展」—— 展开成多条反而稀释了原意。
///
/// ## 提示词要点
///
/// - 要求「独立、完整、无需上下文即可理解」
/// - 明确「补全指代」
/// - 明确「如果原问题本身已完整，保持原样」
pub const REWRITE_PROMPT: &str = "\
你是一个技术知识库的检索助手。用户会问一个问题，你的任务是把它改写成**一个自包含的检索式**。

请严格遵守以下规则：

1. 改写后的检索式必须**独立、完整** —— 不看对话历史也能完全理解在问什么。
2. 如果原问题里有「它」「这个」「那个」「上面说的」等**指代**，
   请根据上下文补全成明确的名词。
3. 如果原问题里省略了主语（比如「和微调有什么区别」），补全主语。
4. 如果原问题**已经自包含**，就保持原样，只做轻微的措辞优化。
5. 用**陈述式或疑问式均可**，但要保留原意，不要增加新信息。
6. **只输出改写后的检索式本身**，一行，不要编号、不要解释、不要引号。

示例：

用户问题：那它训练成本高吗？
输出：RAG 和微调相比，哪种方式的训练成本更高

用户问题：{question}
输出：";

/// Decompose 的提示词。
///
/// ## Decompose 在干什么
///
/// 复合问题问的是**多个方面**，单一向量检索无法同时覆盖：
///
/// ```text
/// 用户：光合作用的光反应和暗反应分别在什么位置进行？各自的作用是什么？
/// ```
///
/// 这句话有两个检索意图：「位置」和「作用」。用整句话检索，
/// 向量会落在「位置」和「作用」的**中间地带** —— 两边都不够近。
///
/// Decompose 把它拆成：
///
/// ```text
/// 1. 光合作用的光反应阶段在什么位置进行？
/// 2. 光合作用的暗反应阶段在什么位置进行？
/// 3. 光合作用的光反应阶段的主要作用是什么？
/// 4. 光合作用的暗反应阶段的主要作用是什么？
/// ```
///
/// 每个子问题单独检索（各自都很具体 → 向量很准），
/// 然后把所有子问题的结果合并。
///
/// ## 关键：子问题必须是「可独立检索」的
///
/// 拆分太粗 → 还是复合问题，没解决问题。
/// 拆分太细 → 「它」这种指代又回来了，反而更糟。
///
/// 所以提示词里明确要求「每个子问题必须是完整的、可独立理解的」。
///
/// ## 与 Multi-Query 的本质区别
///
/// | | Multi-Query | Decompose |
/// |---|---|---|
/// | 意图 | **同一个**意图的不同措辞 | **不同**的意图 |
/// | 效果 | 提升单个意图的召回覆盖 | 覆盖问题的多个方面 |
/// | 结果融合 | 取并集（RRF） | 取并集（RRF），但可能需要按子问题分组 |
pub const DECOMPOSE_PROMPT: &str = "\
你是一个技术知识库的检索助手。用户会问一个**可能包含多个检索意图**的问题，
你的任务是把它拆成**若干个可以独立检索的子问题**。

请严格遵守以下规则：

1. 拆分成 **2 到 4 个**子问题。如果原问题只有一个检索意图，就只输出 1 个。
2. 每个子问题必须**完整、自包含** —— 不看原问题也知道它在问什么，
   不能出现「它」「这个」「上述」这类指代。
3. 每个子问题只针对**一个**检索意图，不要把两个问题塞进一句。
4. 保持原问题的**术语和领域**，不要泛化或引入新话题。
5. 严格按下面的格式输出，每行一个，编号从 1 开始，**不要任何其他内容**：

```
1. 第一个子问题
2. 第二个子问题
3. 第三个子问题
```

示例：

用户问题：光合作用的光反应和暗反应分别在什么位置进行？各自的作用是什么？
输出：
1. 光合作用的光反应阶段发生在什么位置？
2. 光合作用的暗反应阶段发生在什么位置？
3. 光合作用的光反应阶段的主要作用是什么？
4. 光合作用的暗反应阶段的主要作用是什么？

用户问题：{question}
输出：";

#[cfg(test)]
mod tests {
    use super::*;

    /// 提示词里必须有 `{question}` 占位符。
    #[test]
    fn all_prompts_have_placeholder() {
        for (name, p) in [
            ("HYDE", HYDE_PROMPT),
            ("MULTI_QUERY", MULTI_QUERY_PROMPT),
            ("REWRITE", REWRITE_PROMPT),
            ("DECOMPOSE", DECOMPOSE_PROMPT),
        ] {
            assert!(
                p.contains("{question}"),
                "{name} 提示词缺少 {{question}} 占位符"
            );
        }
    }

    /// 提示词不能为空，也不能短得没法用。
    #[test]
    fn prompts_are_substantial() {
        for (name, p) in [
            ("HYDE", HYDE_PROMPT),
            ("MULTI_QUERY", MULTI_QUERY_PROMPT),
            ("REWRITE", REWRITE_PROMPT),
            ("DECOMPOSE", DECOMPOSE_PROMPT),
        ] {
            assert!(p.len() > 200, "{name} 提示词太短（{} 字节）", p.len());
        }
    }

    /// 多条输出的策略必须要求编号列表 —— 解析器靠它切分。
    #[test]
    fn list_prompts_demand_numbering() {
        for (name, p) in [
            ("MULTI_QUERY", MULTI_QUERY_PROMPT),
            ("DECOMPOSE", DECOMPOSE_PROMPT),
        ] {
            assert!(p.contains("1."), "{name} 提示词要求了编号格式");
            assert!(p.contains("编号"), "{name} 提示词提到了编号");
        }
    }
}

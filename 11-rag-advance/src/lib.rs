//! 11-rag-advance —— 高级数据处理：把「复杂文档」变成可检索的结构化数据。
//!
//! ## 本项目解决什么问题
//!
//! 04~10 全部假设文档是「规整的 Markdown」—— 有标题层级、正文成段。
//! 现实里的企业文档不是这样：年报、论文、技术手册里到处是
//! **表格**、**图**、**多栏排版**、**扫描页**。
//!
//! 这些内容一旦被压平成纯文本，语义就永久丢失了：
//!
//! ```text
//! 原始表格          压平之后
//! ┌────┬─────┐     Flat text  none  column major  low
//! │策略│ 表格 │  →  「Flat text none column major low」
//! ├────┼─────┤        （读起来像一句话，没人知道「低」对应哪一列）
//! │策略│ 表格 │
//! └────┴─────┘
//! ```
//!
//! 本项目做四件事：
//!
//! | 模块 | 做什么 |
//! |---|---|
//! | [`parser::table`] | 用**几何**把表格还原成网格（不跑模型） |
//! | [`parser::image`] | 从 PDF 里抽出内嵌图片，落盘 + 生成可检索的描述 |
//! | [`parser::layout`] | 识别标题层级，产出结构化的文档树 |
//! | [`parser::chunk`] | 结构感知分块：表格整块保留，行内可检索 |
//!
//! ## 主线对照
//!
//! | 项目 | 处理的问题 |
//! |---|---|
//! | 04-rag | 规整文本怎么切块 |
//! | 05~10-rag | 怎么检索、怎么评估、怎么上生产 |
//! | **11-rag-advance** | **不规整的文档怎么变成结构化数据** |

